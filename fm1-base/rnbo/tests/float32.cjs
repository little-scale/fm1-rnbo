const assert=require('node:assert/strict');
const {float32}=require('../tools/float32.cjs');
const input='// 0.8\n/* 3.14 */ const char *s="1.23"; float a=0.8,b=1.,c=.5,d=1e-3,e=2.0f; int n=123,mask=0xff; double t=0.0;';
